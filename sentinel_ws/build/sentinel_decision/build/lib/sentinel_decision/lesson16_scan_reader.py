#!/usr/bin/env python3

"""
========================================================
RoboMaster 哨兵机器人
第16课：读取 /scan 并计算最近障碍物方向
========================================================

上一课：

    模拟激光雷达
        ↓
      /scan

这一课：

      /scan
        ↓
    Subscriber
        ↓
    LaserScan
        ↓
    找到最近距离
        ↓
    计算对应角度

最终得到：

    最近障碍物距离
    最近障碍物方向

例如：

    距离 = 2.00 m
    方向 = 0.0°

========================================================
"""

import rclpy

from rclpy.node import Node

from sensor_msgs.msg import LaserScan

import math


# ========================================================
# 创建雷达数据读取节点
# ========================================================

class ScanReader(Node):

    def __init__(self):

        super().__init__(
            "lesson16_scan_reader"
        )


        # =================================================
        # 创建 Subscriber
        # =================================================

        self.subscription = self.create_subscription(

            LaserScan,

            "/scan",

            self.scan_callback,

            10
        )


        self.get_logger().info(

            "第16课：正在等待 /scan 数据..."
        )


    # ====================================================
    # /scan 回调函数
    # ====================================================

    def scan_callback(self, scan):

        """
        每收到一帧 LaserScan，就执行一次。

        scan.ranges：

            保存每个方向的距离。
        """


        # ------------------------------------------------
        # 初始化最近距离
        # ------------------------------------------------

        min_distance = float("inf")


        # ------------------------------------------------
        # 初始化最近障碍物的角度
        # ------------------------------------------------

        min_angle = 0.0


        # =================================================
        # 遍历所有雷达数据
        # =================================================

        for i, distance in enumerate(scan.ranges):


            # ------------------------------------------------
            # 检查数据是否有效
            # ------------------------------------------------

            # 有些真实雷达可能返回：

            # NaN
            # inf

            # 这些数据不能直接参与计算。

            if not math.isfinite(distance):

                continue


            # ------------------------------------------------
            # 检查距离是否在合法范围
            # ------------------------------------------------

            if distance < scan.range_min:

                continue


            if distance > scan.range_max:

                continue


            # =================================================
            # 如果发现更近的障碍物
            # =================================================

            if distance < min_distance:

                min_distance = distance


                # ---------------------------------------------
                # 根据数组下标计算角度
                # ---------------------------------------------

                min_angle = (

                    scan.angle_min

                    + i * scan.angle_increment
                )


        # =================================================
        # 如果没有找到有效数据
        # =================================================

        if min_distance == float("inf"):

            self.get_logger().warn(

                "没有找到有效的雷达数据"
            )

            return


        # =================================================
        # 弧度转换成角度
        # =================================================

        angle_degree = math.degrees(

            min_angle
        )


        # =================================================
        # 输出结果
        # =================================================

        self.get_logger().info(

            f"最近障碍物："
            f"距离 = {min_distance:.2f} m，"
            f"方向 = {angle_degree:.1f}°"
        )


# ========================================================
# main
# ========================================================

def main(args=None):

    rclpy.init(args=args)


    node = ScanReader()


    try:

        rclpy.spin(node)


    except KeyboardInterrupt:

        pass


    node.destroy_node()

    rclpy.shutdown()


# ========================================================
# 程序入口
# ========================================================

if __name__ == "__main__":

    main()