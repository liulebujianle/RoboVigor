#!/usr/bin/env python3

"""
RoboMaster 哨兵导航与决策系统

第15课：
读取 LaserScan 激光雷达数据

本课目标：

1. 创建 /scan
2. 发布模拟 LaserScan
3. 订阅 /scan
4. 读取 ranges
5. 找出最近障碍物

本课暂时不接真实激光雷达。

以后真实雷达会直接提供：

    /scan

而我们的程序只需要订阅它。
"""


# =====================================================
# ROS2
# =====================================================

import rclpy

from rclpy.node import Node


# =====================================================
# LaserScan 消息
# =====================================================

from sensor_msgs.msg import LaserScan


# =====================================================
# 数学库
# =====================================================

import math


# =====================================================
# LaserScan 发布节点
# =====================================================

class LaserScanPublisher(Node):

    """
    模拟一个激光雷达。

    发布：

        /scan
    """

    def __init__(self):

        super().__init__(
            "laser_scan_publisher"
        )


        # =================================================
        # 创建 Publisher
        # =================================================

        self.publisher = self.create_publisher(

            LaserScan,

            "/scan",

            10
        )


        # =================================================
        # Timer
        # =================================================

        self.timer = self.create_timer(

            0.1,

            self.publish_scan
        )


        self.get_logger().info(

            "LaserScan Publisher Start!"
        )


    # =====================================================
    # 发布模拟雷达
    # =====================================================

    def publish_scan(self):

        # 创建 LaserScan 消息

        scan = LaserScan()


        # =================================================
        # 时间
        # =================================================

        scan.header.stamp = (

            self.get_clock().now().to_msg()
        )


        # =================================================
        # 雷达坐标系
        # =================================================

        scan.header.frame_id = "laser"


        # =================================================
        # 扫描角度
        # =================================================

        # 从 -180° 到 +180°

        scan.angle_min = -math.pi

        scan.angle_max = math.pi


        # =================================================
        # 角度间隔
        # =================================================

        scan.angle_increment = math.radians(1.0)


        # =================================================
        # 雷达扫描时间
        # =================================================

        scan.time_increment = 0.0

        scan.scan_time = 0.1


        # =================================================
        # 雷达有效距离
        # =================================================

        scan.range_min = 0.1

        scan.range_max = 10.0


        # =================================================
        # 模拟 360 个距离
        # =================================================

        ranges = []

        for i in range(360):

            # 默认：

            # 所有方向 5 米没有障碍物

            distance = 5.0


            # -------------------------------------------------
            # 模拟机器人前方存在障碍物
            # -------------------------------------------------

            # 0°附近：

            # 距离 = 2 米

            if i < 5 or i > 355:

                distance = 2.0


            ranges.append(distance)


        # =================================================
        # 写入 LaserScan
        # =================================================

        scan.ranges = ranges


        # =================================================
        # 发布
        # =================================================

        self.publisher.publish(scan)


# =====================================================
# LaserScan 订阅节点
# =====================================================

class LaserScanSubscriber(Node):

    """
    订阅：

        /scan

    然后寻找：

        最近障碍物
    """

    def __init__(self):

        super().__init__(
            "laser_scan_subscriber"
        )


        # =================================================
        # 创建 Subscriber
        # =================================================

        self.subscription = self.create_subscription(

            LaserScan,

            "/scan",

            self.scan_callback,

            10
        )


        self.get_logger().info(

            "LaserScan Subscriber Start!"
        )


    # =====================================================
    # 收到 LaserScan
    # =====================================================

    def scan_callback(self, scan):

        """
        每收到一帧 LaserScan
        就执行一次。

        scan.ranges：

            保存所有距离。
        """


        # =================================================
        # 获取距离数据
        # =================================================

        ranges = scan.ranges


        # =================================================
        # 过滤无效数据
        # =================================================

        valid_ranges = []


        for distance in ranges:

            # 判断：

            # 不是 NaN
            # 不是无穷大
            # 在有效范围内

            if math.isfinite(distance):

                if (

                    scan.range_min
                    <= distance
                    <= scan.range_max

                ):

                    valid_ranges.append(distance)


        # =================================================
        # 如果没有有效数据
        # =================================================

        if len(valid_ranges) == 0:

            self.get_logger().warn(

                "No valid laser data!"
            )

            return


        # =================================================
        # 找最近障碍物
        # =================================================

        min_distance = min(
            valid_ranges
        )


        # =================================================
        # 输出
        # =================================================

        self.get_logger().info(

            f"最近障碍物距离: "
            f"{min_distance:.2f} m"
        )


# =====================================================
# 主函数
# =====================================================

def main(args=None):

    # 初始化 ROS2

    rclpy.init(args=args)


    # 创建两个节点

    publisher = LaserScanPublisher()

    subscriber = LaserScanSubscriber()


    # =================================================
    # 使用 MultiThreadedExecutor
    # =================================================

    executor = rclpy.executors.MultiThreadedExecutor()


    executor.add_node(publisher)

    executor.add_node(subscriber)


    # =================================================
    # 开始运行
    # =================================================

    try:

        executor.spin()

    except KeyboardInterrupt:

        pass


    # =================================================
    # 销毁节点
    # =================================================

    publisher.destroy_node()

    subscriber.destroy_node()


    # =================================================
    # 关闭 ROS2
    # =================================================

    rclpy.shutdown()


# =====================================================
# 程序入口
# =====================================================

if __name__ == "__main__":

    main()