#!/usr/bin/env python3

"""
RoboMaster 哨兵导航与决策系统

第 10 课：
比赛剩余时间

本课目标：

建立：

    total_match_time
    match_time
    remaining_time

并让决策系统同时考虑：

    health
    remaining_time

目前使用模拟比赛总时间：

    180 秒

注意：

真正比赛时，总比赛时间应该根据实际比赛规则修改。
"""


# =====================================================
# 导入 ROS2
# =====================================================

import rclpy

from rclpy.node import Node


# =====================================================
# 导入消息
# =====================================================

from std_msgs.msg import Int32


# =====================================================
# RobotState
# =====================================================

class RobotState:

    """
    RobotState：

    保存机器人当前状态。
    """

    def __init__(self):

        # =================================================
        # 机器人血量
        # =================================================

        self.health = 100


        # =================================================
        # 机器人位置
        # =================================================

        self.x = 0.0

        self.y = 0.0


        # =================================================
        # 机器人朝向
        # =================================================

        self.yaw = 0.0


        # =================================================
        # 比赛总时间
        # =================================================

        # 当前假设比赛总时间为 180 秒。

        self.total_match_time = 180.0


        # =================================================
        # 当前比赛时间
        # =================================================

        self.match_time = 0.0


        # =================================================
        # 剩余比赛时间
        # =================================================

        self.remaining_time = self.total_match_time


# =====================================================
# DecisionEngine
# =====================================================

class DecisionEngine:

    """
    决策引擎。

    当前考虑两个因素：

        1. health
        2. remaining_time
    """

    def decide(self, state):

        """
        根据 RobotState 做决策。

        返回：

            GO_TO_POINT
            RETURN_BASE
        """

        # =================================================
        # 情况 1：
        # 血量非常低
        # =================================================

        if state.health < 30:

            # ---------------------------------------------
            # 如果比赛还剩很多时间
            # ---------------------------------------------

            if state.remaining_time > 20:

                return "RETURN_BASE"


            # ---------------------------------------------
            # 如果比赛马上结束
            # ---------------------------------------------

            else:

                return "STAY_AND_FIGHT"


        # =================================================
        # 情况 2：
        # 血量正常
        # =================================================

        else:

            return "GO_TO_POINT"


# =====================================================
# DecisionNode
# =====================================================

class DecisionNode(Node):

    """
    ROS2 决策节点。
    """

    def __init__(self):

        # =================================================
        # 初始化 ROS2
        # =================================================

        super().__init__(
            "remaining_time_decision_node"
        )


        # =================================================
        # 创建 RobotState
        # =================================================

        self.state = RobotState()


        # =================================================
        # 创建 DecisionEngine
        # =================================================

        self.decision_engine = DecisionEngine()


        # =================================================
        # 订阅血量
        # =================================================

        self.health_subscription = self.create_subscription(

            Int32,

            "/sentinel/health",

            self.health_callback,

            10
        )


        # =================================================
        # 创建 Timer
        # =================================================

        # 每 1 秒执行一次：

        # update_time_and_decision()

        self.timer = self.create_timer(

            1.0,

            self.update_time_and_decision
        )


        # =================================================
        # 启动信息
        # =================================================

        self.get_logger().info(

            "Remaining Time Decision Node Start!"
        )


    # =====================================================
    # 血量 Callback
    # =====================================================

    def health_callback(self, msg):

        """
        接收血量。

        ROS2 Topic：

            /sentinel/health
        """

        self.state.health = msg.data


    # =====================================================
    # 更新时间 + 决策
    # =====================================================

    def update_time_and_decision(self):

        """
        每秒执行一次。

        流程：

            当前时间
                 ↓
            + 1 秒
                 ↓
            计算剩余时间
                 ↓
            DecisionEngine
                 ↓
            输出决策
        """

        # =================================================
        # 1. 比赛时间增加
        # =================================================

        self.state.match_time += 1.0


        # =================================================
        # 2. 计算剩余时间
        # =================================================

        self.state.remaining_time = (

            self.state.total_match_time
            - self.state.match_time
        )


        # =================================================
        # 3. 防止剩余时间出现负数
        # =================================================

        if self.state.remaining_time < 0:

            self.state.remaining_time = 0.0


        # =================================================
        # 4. 获取决策
        # =================================================

        decision = self.decision_engine.decide(

            self.state
        )


        # =================================================
        # 5. 输出状态
        # =================================================

        self.get_logger().info(

            f"Health = {self.state.health}"
        )


        self.get_logger().info(

            f"Match Time = "
            f"{self.state.match_time:.1f} s"
        )


        self.get_logger().info(

            f"Remaining Time = "
            f"{self.state.remaining_time:.1f} s"
        )


        self.get_logger().info(

            f"Decision = {decision}"
        )


# =====================================================
# main
# =====================================================

def main(args=None):

    # 初始化 ROS2

    rclpy.init(args=args)


    # 创建节点

    node = DecisionNode()


    # 保持节点运行

    rclpy.spin(node)


    # 关闭 ROS2

    rclpy.shutdown()


# =====================================================
# 程序入口
# =====================================================

if __name__ == "__main__":

    main()