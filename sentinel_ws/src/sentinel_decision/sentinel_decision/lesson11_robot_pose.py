#!/usr/bin/env python3

"""
RoboMaster 哨兵导航与决策系统

第 11 课：
建立机器人位姿状态

本课目标：

建立机器人：

    x
    y
    yaw

并将这些数据保存到：

    RobotState

注意：

本课暂时不接真实 SLAM。

我们使用 Timer 模拟机器人移动。

以后会把这里的模拟数据替换成：

    SLAM / TF2
        ↓
    真实机器人位姿
"""


# =====================================================
# 导入 ROS2
# =====================================================

import rclpy

from rclpy.node import Node


# =====================================================
# RobotState
# =====================================================

class RobotState:

    """
    RobotState：

    保存机器人当前状态。

    当前包括：

        health
        x
        y
        yaw
        total_match_time
        match_time
        remaining_time
    """

    def __init__(self):

        # =================================================
        # 血量
        # =================================================

        self.health = 100


        # =================================================
        # X 坐标
        # =================================================

        self.x = 0.0


        # =================================================
        # Y 坐标
        # =================================================

        self.y = 0.0


        # =================================================
        # yaw
        # =================================================

        self.yaw = 0.0


        # =================================================
        # 比赛总时间
        # =================================================

        self.total_match_time = 180.0


        # =================================================
        # 当前比赛时间
        # =================================================

        self.match_time = 0.0


        # =================================================
        # 剩余比赛时间
        # =================================================

        self.remaining_time = 180.0


# =====================================================
# Pose Simulator
# =====================================================

class PoseSimulator:

    """
    PoseSimulator：

    用于模拟机器人移动。

    真实机器人中：

        SLAM / TF2
            ↓
        真实 x/y/yaw

    现在：

        Simulator
            ↓
        模拟 x/y/yaw
    """

    def update(self, state):

        """
        模拟机器人向 X 方向移动。

        每次调用：

            x += 0.1

        所以：

            0.0
            0.1
            0.2
            0.3
            ...
        """

        # =================================================
        # 模拟 X 方向移动
        # =================================================

        state.x += 0.1


        # =================================================
        # 暂时保持 Y 不变
        # =================================================

        state.y = 0.0


        # =================================================
        # 暂时保持 yaw 不变
        # =================================================

        state.yaw = 0.0


# =====================================================
# RobotPoseNode
# =====================================================

class RobotPoseNode(Node):

    """
    ROS2 节点。

    功能：

        1. 更新时间
        2. 模拟机器人位姿
        3. 更新 RobotState
        4. 输出状态
    """

    def __init__(self):

        # =================================================
        # 初始化 ROS2 Node
        # =================================================

        super().__init__(
            "robot_pose_node"
        )


        # =================================================
        # 创建 RobotState
        # =================================================

        self.state = RobotState()


        # =================================================
        # 创建 PoseSimulator
        # =================================================

        self.pose_simulator = PoseSimulator()


        # =================================================
        # 创建 Timer
        # =================================================

        # 每 1 秒更新一次。

        self.timer = self.create_timer(

            1.0,

            self.update
        )


        # =================================================
        # 启动信息
        # =================================================

        self.get_logger().info(

            "Robot Pose Node Start!"
        )


    # =====================================================
    # Update
    # =====================================================

    def update(self):

        """
        每秒执行一次。

        流程：

            更新时间
                ↓
            更新位姿
                ↓
            输出状态
        """

        # =================================================
        # 1. 更新时间
        # =================================================

        self.state.match_time += 1.0


        # =================================================
        # 2. 计算剩余时间
        # =================================================

        self.state.remaining_time = (

            self.state.total_match_time
            - self.state.match_time
        )


        # =================================================
        # 3. 防止剩余时间小于 0
        # =================================================

        if self.state.remaining_time < 0:

            self.state.remaining_time = 0.0


        # =================================================
        # 4. 更新机器人位姿
        # =================================================

        self.pose_simulator.update(

            self.state
        )


        # =================================================
        # 5. 输出机器人位置
        # =================================================

        self.get_logger().info(

            f"Position: "
            f"x={self.state.x:.2f} m, "
            f"y={self.state.y:.2f} m, "
            f"yaw={self.state.yaw:.2f} rad"
        )


        # =================================================
        # 6. 输出比赛时间
        # =================================================

        self.get_logger().info(

            f"Match Time: "
            f"{self.state.match_time:.1f} s"
        )


        self.get_logger().info(

            f"Remaining Time: "
            f"{self.state.remaining_time:.1f} s"
        )


# =====================================================
# main
# =====================================================

def main(args=None):

    # 初始化 ROS2

    rclpy.init(args=args)


    # 创建节点

    node = RobotPoseNode()


    # 保持节点运行

    rclpy.spin(node)


    # 关闭 ROS2

    rclpy.shutdown()


# =====================================================
# 程序入口
# =====================================================

if __name__ == "__main__":

    main()